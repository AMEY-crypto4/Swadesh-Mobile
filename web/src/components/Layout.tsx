import { NavLink, Outlet } from 'react-router-dom';
import clsx from 'clsx';
import { Activity, BookOpen, Code2, Gauge, History, LayoutDashboard, ListOrdered, LogOut, Megaphone, ShieldCheck, Users, Wifi, WifiOff, Radio } from 'lucide-react';
import { useAuth } from '../lib/auth';
import { useLive, useNow } from '../lib/live';

export function ConnectionChip() {
  const { connection, lastMessageAt } = useLive();
  const now = useNow(1000);
  const age = lastMessageAt ? Math.max(0, Math.round((now - lastMessageAt) / 1000)) : null;
  if (connection === 'live') {
    return <span role="status" className="inline-flex items-center gap-1.5 rounded-full bg-emerald-100 px-2.5 py-1 text-xs font-medium text-emerald-800"><Wifi className="h-3.5 w-3.5" aria-hidden />Live{age !== null && age > 45 ? ` · quiet for ${age}s` : ''}</span>;
  }
  return (
    <span role="status" className="inline-flex items-center gap-1.5 rounded-full bg-amber-100 px-2.5 py-1 text-xs font-medium text-amber-900">
      <WifiOff className="h-3.5 w-3.5" aria-hidden />{connection === 'connecting' ? 'Connecting…' : `Reconnecting — data may be stale${age !== null ? ` (last update ${age}s ago)` : ''}`}
    </span>
  );
}


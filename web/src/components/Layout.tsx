export function SimulationBanner() {
  const { simulated } = useLive();
  if (!simulated) return null;
  return (
    <div className="border-b border-amber-200 bg-amber-50 px-4 py-1.5 text-center text-xs text-amber-900">
      <Radio className="mr-1 inline h-3 w-3" aria-hidden /><strong>Simulated telephony.</strong> Calls, agents and carrier results on this screen are generated by the demo engine — no real PSTN calls or SMS are placed.
    </div>
  );
}

